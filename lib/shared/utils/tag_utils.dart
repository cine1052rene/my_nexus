/// 태그 입력 파싱.
///
/// 태그는 `#` **없이** 저장한다. `#`은 화면에 그릴 때만 붙이는 장식이라
/// (`'#$tag'`), 값에 `#`을 포함시키면 표시가 `##태그`가 되고 같은 이름의
/// 기존 태그와 다른 태그로 취급돼 필터·태그 목록이 갈라진다.
///
/// 그래서 입력은 `#`을 허용하되 저장 직전에 떼어낸다.
/// 사용자는 `뜨개질, 초보` 로도, `#뜨개질 #초보` 로도 쓸 수 있다.
///
/// 구분자로 공백을 허용해도 기존 데이터는 깨지지 않는다
/// (2026-09-01 기준 저장된 태그 118종 중 공백을 포함한 것은 0건).
List<String> parseTags(String raw) {
  return raw
      .split(RegExp(r'[,\s]+'))
      // 앞에 붙은 #을 모두 제거. '#'만 입력된 경우는 빈 문자열이 돼 걸러진다.
      .map((t) => t.replaceFirst(RegExp(r'^#+'), '').trim())
      .where((t) => t.isNotEmpty)
      // 같은 태그를 두 번 적어도 하나로 (LinkedHashSet이라 입력 순서 유지)
      .toSet()
      .toList();
}

/// 본문(AI 큐레이션 결과 등)에서 해시태그를 추출한다.
///
/// 예전 정규식 `#(\S+)` 은 마크다운 제목 `## 📌 개요` 에서
/// 첫 `#` 뒤의 `\S+` 가 두 번째 `#` 를 잡아 **태그 "#"** 를 만들어냈다.
/// 큐레이션할 때마다 의미 없는 태그가 하나씩 쌓이고 있었다(실제 63건 발생).
///
/// `[^\s#]+` 로 바꾸면 `#` 바로 뒤에 `#`이나 공백이 오는 경우가 배제되므로
/// 마크다운 제목(`#`, `##`, `### `)은 더 이상 매칭되지 않는다.
List<String> extractHashtags(String text) {
  return RegExp(r'#([^\s#]+)')
      .allMatches(text)
      .map((m) => m.group(1)!.trim())
      .where((t) => t.isNotEmpty)
      .toSet()
      .toList();
}
