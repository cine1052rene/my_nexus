/// 한국 음력 변환기 (표 기반, 2023-12 ~ 2034-12-11 전날까지)
///
/// 예전 구현은 "홀수달 30일·짝수달 29일" 근사 계산이라 값이 틀렸다
/// (2026-11-19 실제 음력 10월 11일 → 화면에 9일·10일로 제각각 표시, 윤달 무시).
///
/// 이 표는 음력 각 달의 시작일(초하루)을 담는다. 만드는 법:
///   삭(新月) 순간을 한국 표준시(KST, UTC+9)로 계산해 그날을 초하루로,
///   동지가 든 달을 11월로, 중기(中氣)가 없는 달을 윤달로 정했다(PyEphem).
///   한국천문연구원 역법과 같은 규칙이다. 검증: 2024~2034 설날 11개·추석 11개,
///   윤달(2025 윤6·2028 윤5·2031 윤3·2033 윤11) 모두 공표 날짜와 일치.
///   중국 기준표(UTC+8)는 2027 설날 등이 하루 어긋나므로 쓰면 안 된다.
/// 범위 밖 날짜는 틀린 값을 보여주느니 null을 돌려 화면에서 숨긴다.
