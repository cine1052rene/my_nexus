    const gan = ['갑', '을', '병', '정', '무', '기', '경', '신', '임', '계'];
    const ji = ['자', '축', '인', '묘', '진', '사', '오', '미', '신', '유', '술', '해'];
    const animals = ['쥐', '소', '호랑이', '토끼', '용', '뱀', '말', '양', '원숭이', '닭', '개', '돼지'];
    final g = gan[(year - 4) % 10];
    final j = ji[(year - 4) % 12];
    final a = animals[(year - 4) % 12];
    return '$g$j년($a)';
  }

