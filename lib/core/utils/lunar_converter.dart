class LunarDate {
  final int year;
  final int month;
  final int day;
  final bool isLeap;

  const LunarDate({
    required this.year,
    required this.month,
    required this.day,
    this.isLeap = false,
  });

  @override
  String toString() => '음력 ${isLeap ? '윤' : ''}$month월 $day일';

  String toFullString() {
    final ganji = LunarConverter.getGanJi(year);
    return '$ganji ${isLeap ? '윤' : ''}$month월 $day일';
  }
}

