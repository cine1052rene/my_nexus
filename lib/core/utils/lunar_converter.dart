  /// (이름은 예전 코드 호환용 — 실제로는 양력→음력 변환)
  static LunarDate? toSolar(DateTime solar) {
    final day = DateTime.utc(solar.year, solar.month, solar.day);
    if (day.isBefore(_months.first.start) || !day.isBefore(_end)) return null;
    // 이진 탐색: day 이하인 마지막 초하루
    var lo = 0, hi = _months.length - 1;
    while (lo < hi) {
      final mid = (lo + hi + 1) >> 1;
      if (_months[mid].start.isAfter(day)) {
        hi = mid - 1;
      } else {
        lo = mid;
      }
    }
    final m = _months[lo];
    return LunarDate(
      year: m.year,
      month: m.month,
      day: day.difference(m.start).inDays + 1,
      isLeap: m.leap,
    );
  }

  /// 천간지지 (간지) 계산
